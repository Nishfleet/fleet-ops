#!/usr/bin/env python3
# bin/render-pi-agents-md
#
# Deterministic generator for the Pi AGENTS.md files (~/AGENTS.md and
# ~/.pi/agent/AGENTS.md) from a single canonical source.
#
# Reads the canonical source at lib/pi-agents-md/canonical.md and writes
# both target files identically. Kills the 2-copy drift class:
# ~/AGENTS.md and ~/.pi/agent/AGENTS.md were near-duplicates that could
# drift independently; now both are built from one source.
#
# The canonical file carries a header comment block (<!-- ... --> lines)
# that the render strips. The output files receive a generated-at-the-top
# comment, the title line, and the canonical body.
#
# Modes:
#   --render    write regenerated content to both target files
#   --check     exit nonzero if either target differs from what would be
#               generated (i.e. hand-edit drift detected)
#   --write     alias for --render
#
# Drift detection is byte-level: render to strings, compare against what's
# on disk. A drift means the canonical source was not kept in sync — edit
# lib/pi-agents-md/canonical.md and re-run --render, never hand-edit the
# generated files.

import argparse
import sys
from pathlib import Path

CANONICAL_DEFAULT = Path(__file__).resolve().parent.parent / "lib" / "pi-agents-md" / "canonical.md"
TARGETS = [
    Path("/home/nish/AGENTS.md"),
    Path("/home/nish/.pi/agent/AGENTS.md"),
]
_canonical_path: Path = CANONICAL_DEFAULT

GENERATED_HEADER = (
    "<!-- GENERATED from lib/pi-agents-md/canonical.md "
    "by bin/render-pi-agents-md.py.\n"
    "DO NOT EDIT this file directly — edit the canonical source and re-"
    "render. -->\n"
)
TITLE_LINE = "# AGENTS.md — context for Pi on netcup-rs2000\n"


def load_canonical(path: Path | None = None) -> str:
    """Load the canonical body, stripping the header comment block.

    The canonical file starts with an HTML comment block that may span
    multiple lines (some lines have `<!--` without a closing `-->`,
    others are continuation lines with just `-->` at the end).  We strip
    every leading line until we hit the first non-blank, non-comment
    line — that is where the canonical body begins.

    A line is part of the header if it is blank, starts with `<!--`,
    or continues a prior unterminated `<!--` comment (i.e. the prior
    line started with `<!--` but did not end with `-->`).  The comment
    can span an arbitrary number of lines; the last continuation line
    ends with `-->`.
    """
    if path is None:
        path = _canonical_path
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    body_start = 0
    in_comment = False
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped == "":
            body_start = i + 1
            continue
        if stripped.startswith("<!--"):
            in_comment = True
            if stripped.endswith("-->"):
                in_comment = False
            body_start = i + 1
            continue
        if in_comment:
            # Continuation of a prior unterminated <!-- comment.
            if stripped.endswith("-->"):
                in_comment = False
            body_start = i + 1
            continue
        # First non-blank, non-comment line.
        body_start = i
        break
    body = "".join(lines[body_start:])
    if not body.strip():
        raise ValueError(f"canonical body is empty after stripping header in {path}")
    return body


def render() -> str:
    """Produce a single rendered output string for a target file."""
    body = load_canonical()
    return GENERATED_HEADER + "\n" + TITLE_LINE + "\n" + body


def drift_report(target: Path, expected: str) -> str | None:
    """Return None if the target matches; else a human-readable drift notice."""
    current = target.read_text(encoding="utf-8")
    if current == expected:
        return None
    return f"DRIFT in {target}"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description="Regenerate (or --check) Pi AGENTS.md files from the canonical source."
    )
    parser.add_argument("--render", action="store_true", help="write regenerated content")
    parser.add_argument("--write", action="store_true", help="alias for --render")
    parser.add_argument(
        "--check", action="store_true", help="exit nonzero on drift from canonical (default)"
    )
    parser.add_argument("--canonical", type=Path, default=CANONICAL_DEFAULT, help="canonical source path")
    args = parser.parse_args(argv)
    do_render = args.render or args.write
    do_check = args.check or (not do_render)

    global _canonical_path
    _canonical_path = args.canonical

    expected = render()
    failed: list[str] = []

    for target in TARGETS:
        if do_check:
            report = drift_report(target, expected)
            if report is not None:
                failed.append(report)
        if do_render:
            target.write_text(expected, encoding="utf-8")

    if do_render:
        for target in TARGETS:
            print(f"rendered {target}")

    if failed:
        for line in failed:
            print(line, file=sys.stderr)
        print(
            f"\n{len(failed)} target(s) drifted from canonical."
            "\nEdit lib/pi-agents-md/canonical.md and run"
            " bin/render-pi-agents-md.py --render to regenerate.",
            file=sys.stderr,
        )
        return 1

    print(f"OK (checked): {len(TARGETS)} target(s) match canonical")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))